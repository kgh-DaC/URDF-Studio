"""Build a ROS 2 description package zip (urdf-authoring section 6).

<pkg>/{package.xml, CMakeLists.txt, urdf/<robot>.urdf, meshes/, launch/display.launch.py, rviz/display.rviz}
Meshes referenced as package://<any>/meshes/<file> that exist in the upload store are copied,
and their references are rewritten to package://<pkg>/meshes/<file>.
"""
from __future__ import annotations

import io
import re
import xml.etree.ElementTree as ET
import zipfile
from xml.sax.saxutils import escape as xml_escape

from builder import package_name
from storage import mesh_path

MESH_REF = re.compile(r"package://[^/\"']+/meshes/([A-Za-z0-9_][A-Za-z0-9_.\-]*\.(?:stl|dae|obj))", re.I)


def robot_name_of(urdf: str) -> str:
    try:
        return ET.fromstring(urdf).get("name") or "robot"
    except ET.ParseError:
        return "robot"


PACKAGE_XML = """<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<package format="3">
  <name>{pkg}</name>
  <version>0.1.0</version>
  <description>URDF description for {robot} (generated by URDF web app)</description>
  <maintainer email="user@example.com">user</maintainer>
  <license>Apache-2.0</license>

  <buildtool_depend>ament_cmake</buildtool_depend>

  <exec_depend>robot_state_publisher</exec_depend>
  <exec_depend>joint_state_publisher_gui</exec_depend>
  <exec_depend>rviz2</exec_depend>
  <exec_depend>xacro</exec_depend>
  <exec_depend>launch_ros</exec_depend>

  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
"""

CMAKELISTS = """cmake_minimum_required(VERSION 3.8)
project({pkg})

find_package(ament_cmake REQUIRED)

install(DIRECTORY urdf meshes launch rviz
  DESTINATION share/${{PROJECT_NAME}}
)

ament_package()
"""

LAUNCH = '''import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.substitutions import Command
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue


def generate_launch_description():
    share = get_package_share_directory("{pkg}")
    urdf_path = os.path.join(share, "urdf", "{robot}.urdf")
    rviz_path = os.path.join(share, "rviz", "display.rviz")
    robot_description = ParameterValue(Command(["xacro ", urdf_path]), value_type=str)

    return LaunchDescription([
        Node(
            package="robot_state_publisher",
            executable="robot_state_publisher",
            parameters=[{{"robot_description": robot_description}}],
        ),
        Node(package="joint_state_publisher_gui", executable="joint_state_publisher_gui"),
        Node(package="rviz2", executable="rviz2", arguments=["-d", rviz_path]),
    ])
'''

RVIZ = """Panels:
  - Class: rviz_common/Displays
    Name: Displays
Visualization Manager:
  Class: ""
  Displays:
    - Class: rviz_default_plugins/Grid
      Name: Grid
      Enabled: true
    - Class: rviz_default_plugins/RobotModel
      Name: RobotModel
      Enabled: true
      Description Source: Topic
      Description Topic:
        Value: /robot_description
    - Class: rviz_default_plugins/TF
      Name: TF
      Enabled: false
  Global Options:
    Fixed Frame: base_link
  Views:
    Current:
      Class: rviz_default_plugins/Orbit
      Distance: 2.0
"""

README = """# {pkg}

```bash
cd ~/ros2_ws/src && unzip {pkg}.zip
cd ~/ros2_ws && colcon build --packages-select {pkg}
source install/setup.bash
ros2 launch {pkg} display.launch.py
```
"""


def build_package_zip(urdf: str) -> tuple[bytes, str]:
    robot = robot_name_of(urdf)
    file_robot = re.sub(r"[^A-Za-z0-9_\-]", "_", robot)
    pkg = package_name(robot)
    files = sorted({m.group(1) for m in MESH_REF.finditer(urdf)})
    present = [f for f in files if mesh_path(f) is not None]
    out_urdf = MESH_REF.sub(lambda m: f"package://{pkg}/meshes/{m.group(1)}"
                            if m.group(1) in present else m.group(0), urdf)

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        # robot name is untrusted text from the URDF: escape it for XML (QA E4)
        z.writestr(f"{pkg}/package.xml", PACKAGE_XML.format(pkg=pkg, robot=xml_escape(robot)))
        z.writestr(f"{pkg}/CMakeLists.txt", CMAKELISTS.format(pkg=pkg))
        z.writestr(f"{pkg}/urdf/{file_robot}.urdf", out_urdf)
        z.writestr(f"{pkg}/launch/display.launch.py", LAUNCH.format(pkg=pkg, robot=file_robot))
        z.writestr(f"{pkg}/rviz/display.rviz", RVIZ)
        z.writestr(f"{pkg}/README.md", README.format(pkg=pkg))
        z.writestr(f"{pkg}/meshes/.keep", "")
        for f in present:
            z.write(mesh_path(f), f"{pkg}/meshes/{f}")
    return buf.getvalue(), pkg
